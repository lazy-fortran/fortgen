module fortgen_tensor_emit
    !! Tensor-product schedule around a neutral scalar IR leaf. No basis,
    !! quadrature, geometry, or assembly mathematics is supplied implicitly.
    use fortgen_string, only: str_t, str, chars
    use fortgen_buffer, only: buffer_t
    use fortgen_layout, only: wrap_fortran_source
    use fortgen_names, only: valid_fortran_name
    use fortgen_kernel_ir, only: kernel_ir_t
    use fortgen_kernel_emit, only: kernel_emit_spec_t, emit_fortran_kernel_ir, &
                                   emit_cuda_device_ir, PRECISION_REAL32, &
                                   PRECISION_REAL64
    implicit none
    private
    public :: tensor_kernel_spec_t, emit_tensor_fortran, emit_tensor_cuda

    type :: tensor_kernel_spec_t
        type(str_t) :: name
        integer :: dimension = 2
        integer :: nloc = 2
        integer :: nq = 2
        integer :: batch = 8
        integer :: ncoeff = 0
        integer :: precision = PRECISION_REAL64
        logical :: cell_tables = .false.
    end type

contains

    function number(i) result(s)
        integer, intent(in) :: i
        character(:), allocatable :: s
        character(32) :: tmp
        write (tmp, '(i0)') i
        s = trim(tmp)
    end function

    subroutine validate(t, leaf, ok, message)
        type(tensor_kernel_spec_t), intent(in) :: t
        type(kernel_emit_spec_t), intent(in) :: leaf
        logical, intent(out) :: ok
        character(:), allocatable, intent(out) :: message
        ok = .false.
        message = 'tensor kernel: invalid name or compile-time extents'
        if (.not. valid_fortran_name(chars(t%name))) return
        if (len(chars(t%name)) > 48) return
        if (t%dimension /= 2 .and. t%dimension /= 3) return
        if (t%nloc < 2 .or. t%nloc > 9) return
        if (t%nq /= t%nloc .and. t%nq /= t%nloc + 1) return
        if (t%batch < 1 .or. t%batch > 256 .or. t%ncoeff < 0) return
        if (t%precision /= PRECISION_REAL32 .and. &
            t%precision /= PRECISION_REAL64) return
        message = 'tensor kernel: leaf needs d+1+ncoeff inputs and d+1 outputs'
        if (.not. allocated(leaf%args)) return
        if (.not. allocated(leaf%outputs)) return
        if (size(leaf%args) /= t%dimension + 1 + t%ncoeff) return
        if (size(leaf%outputs) /= t%dimension + 1) return
        message = ''
        ok = .true.
    end subroutine

    function emit_tensor_fortran(ir, leaf, t, ok, message) result(source)
        type(kernel_ir_t), intent(in) :: ir
        type(kernel_emit_spec_t), intent(in) :: leaf
        type(tensor_kernel_spec_t), intent(in) :: t
        logical, intent(out) :: ok
        character(:), allocatable, intent(out) :: message
        type(str_t) :: source, scalar
        type(kernel_emit_spec_t) :: ls
        type(buffer_t) :: b
        character(:), allocatable :: name, rk, nb, nn, qq, vv, cc, nt, args
        integer :: ch, axis, dims(3), nd, nqv
        character(:), allocatable :: field

        source = str('')
        call validate(t, leaf, ok, message)
        if (.not. ok) return
        name = chars(t%name)
        ls = leaf
        ls%name = str(name//'_leaf')
        ls%precision = t%precision
        ls%pure_procedure = .true.
        scalar = emit_fortran_kernel_ir(ir, ls, ok, message)
        if (.not. ok) return
        rk = 'real64'
        if (t%precision == PRECISION_REAL32) rk = 'real32'
        nd = t%nloc**t%dimension
        nqv = t%nq**t%dimension
        nb = number(t%batch); nn = number(nd); qq = number(nqv)
        vv = number(max(t%nloc, t%nq)**t%dimension)
        cc = number(t%ncoeff); nt = '1'
        if (t%cell_tables) nt = 'nc'
        call b%line('! Generated by FortGen tensor schedule. Do not edit.')
        call b%line('module '//name//'_module')
        if (t%precision == PRECISION_REAL32) then
            call b%line('use, intrinsic :: iso_fortran_env, only: real32, int32')
        else
            call b%line('use, intrinsic :: iso_fortran_env, only: real64')
        end if
        call b%line('implicit none')
        call b%line('private')
        call b%line('public :: '//name)
        call b%line('contains')
        call b%line('recursive subroutine '//name//'(nc, u, b, db, coef, y)')
        call b%line('integer, intent(in) :: nc')
        call b%line('real('//rk//'), intent(in) :: u('//nb//','//nn//')')
        call b%line('real('//rk//'), intent(in) :: b('//number(t%nq)// &
                    ','//number(t%nloc)//','//number(t%dimension)//','//nt//')')
        call b%line('real('//rk//'), intent(in) :: db('//number(t%nq)// &
                    ','//number(t%nloc)//','//number(t%dimension)//','//nt//')')
        call b%line('real('//rk//'), intent(in) :: coef('//nb//','//qq//','//cc//')')
        call b%line('real('//rk//'), intent(out) :: y('//nb//','//nn//')')
        call b%line('real('//rk//') :: a('//nb//','//vv//'), z('//nb//','//vv//')')
        call b%line('real('//rk//') :: v('//nb//','//qq//',0:'// &
                    number(t%dimension)//'), f('//nb//','//qq//',0:'// &
                    number(t%dimension)//')')
        if (t%precision == PRECISION_REAL32) then
            call b%line('real(real32) :: a_low('//nb//','//vv// &
                        '), z_low('//nb//','//vv//')')
            call b%line('real(real32) :: correction('//nb//'), term('//nb// &
                        '), next('//nb//')')
            call b%line('real(real32) :: ah('//nb//'), al('//nb//'), bh('//nb// &
                        '), bl('//nb//'), prod('//nb//'), residual('//nb//')')
        end if
        call b%line('integer :: l, j, qi')
        call b%line('if (nc < 0 .or. nc > '//nb//') error stop "invalid cell batch"')
        field = 'a(l,j)'
        if (t%precision == PRECISION_REAL32) field = '(a(l,j)+a_low(l,j))'
        do ch = 0, t%dimension
            call copy_cpu(b, 'a(l,j)', 'u(l,j)', nd)
            if (t%precision == PRECISION_REAL32) &
                call copy_cpu(b, 'a_low(l,j)', '0.0_real32', nd)
            dims = t%nloc
            do axis = 1, t%dimension
                call stage_cpu(b, t, dims, axis, ch, .false.)
            end do
            call copy_cpu(b, 'v(l,j,'//number(ch)//')', field, nqv)
        end do
        args = ''
        do ch = 0, t%dimension
            args = args//'v(l,j,'//number(ch)//'),'
        end do
        do ch = 1, t%ncoeff
            args = args//'coef(l,j,'//number(ch)//'),'
        end do
        do ch = 0, t%dimension
            args = args//'f(l,j,'//number(ch)//')'
            if (ch /= t%dimension) args = args//','
        end do
        call b%line('do j = 1, '//qq)
        call b%line('!$omp simd')
        call b%line('do l = 1, nc')
        call b%line('call '//name//'_leaf('//args//')')
        call b%line('end do')
        call b%line('end do')
        call copy_cpu(b, 'y(l,j)', '0.0_'//rk, nd)
        do ch = 0, t%dimension
            call copy_cpu(b, 'a(l,j)', 'f(l,j,'//number(ch)//')', nqv)
            if (t%precision == PRECISION_REAL32) &
                call copy_cpu(b, 'a_low(l,j)', '0.0_real32', nqv)
            dims = t%nq
            do axis = t%dimension, 1, -1
                call stage_cpu(b, t, dims, axis, ch, .true.)
            end do
            call copy_cpu(b, 'y(l,j)', 'y(l,j)+'//field, nd)
        end do
        call b%line('end subroutine')
        call b%line(chars(scalar))
        call b%line('end module')
        source = str(wrap_fortran_source(b%str()))
    end function

    subroutine copy_cpu(b, lhs, rhs, n)
        type(buffer_t), intent(inout) :: b
        character(*), intent(in) :: lhs, rhs
        integer, intent(in) :: n
        call b%line('do j = 1, '//number(n))
        call b%line('!$omp simd')
        call b%line('do l = 1, nc')
        call b%line(lhs//' = '//rhs)
        call b%line('end do')
        call b%line('end do')
    end subroutine

    function balanced_sum(terms) result(expression)
        type(str_t), intent(in) :: terms(:)
        character(:), allocatable :: expression
        type(str_t), allocatable :: level(:)
        integer :: n, i
        level = terms
        n = size(level)
        do while (n > 1)
            do i = 1, n/2
                level(i) = str('('//chars(level(2*i - 1))//'+'// &
                               chars(level(2*i))//')')
            end do
            if (mod(n, 2) == 1) level(n/2 + 1) = level(n)
            n = (n + 1)/2
        end do
        expression = chars(level(1))
    end function balanced_sum

    subroutine stage_cpu(b, t, dims, axis, ch, transpose)
        type(buffer_t), intent(inout) :: b
        type(tensor_kernel_spec_t), intent(in) :: t
        integer, intent(inout) :: dims(3)
        integer, intent(in) :: axis, ch
        logical, intent(in) :: transpose
        integer :: stride, ni, no, total, k
        type(str_t), allocatable :: terms(:), left(:), right(:)
        character(:), allocatable :: mat, table, idx, entry
        stride = product(dims(:axis - 1))
        ni = dims(axis)
        no = t%nq
        if (transpose) no = t%nloc
        dims(axis) = no
        total = product(dims(:t%dimension))
        mat = 'b'
        table = '1'
        if (ch == axis) mat = 'db'
        if (t%cell_tables) table = 'l'
        allocate (terms(ni), left(ni), right(ni))
        do k = 0, ni - 1
            idx = 'mod(j,'//number(stride)//')+'//number(stride)// &
                  '*('//number(k)//'+'//number(ni)//'*(j/'// &
                  number(stride*no)//'))+1'
            if (transpose) then
                entry = mat//'('//number(k + 1)//',qi,'//number(axis)//','//table//')'
            else
                entry = mat//'(qi,'//number(k + 1)//','//number(axis)//','//table//')'
            end if
            left(k + 1) = str(entry)
            right(k + 1) = str('a(l,'//idx//')')
            terms(k + 1) = str(entry//'*a(l,'//idx//')')
        end do
        call b%line('do j = 0, '//number(total - 1))
        call b%line('qi = mod(j/'//number(stride)//','//number(no)//')+1')
        call b%line('!$omp simd')
        call b%line('do l = 1, nc')
        if (t%precision == PRECISION_REAL32) then
            call b%line('z(l,j+1) = 0.0_real32')
            call b%line('correction(l) = 0.0_real32')
            call b%line('end do')
            do k = 1, ni
                call b%line('!$omp simd')
                call b%line('do l = 1, nc')
                ! Split IEEE binary32 significands into 12-bit parts without
                ! multiplying the input by a large splitter (which can overflow).
                call b%line('ah(l) = transfer(iand(transfer('//chars(left(k))// &
                            ',0_int32),not(4095_int32)),0.0_real32)')
                call b%line('al(l) = '//chars(left(k))//'-ah(l)')
                call b%line('bh(l) = transfer(iand(transfer('//chars(right(k))// &
                            ',0_int32),not(4095_int32)),0.0_real32)')
                call b%line('bl(l) = '//chars(right(k))//'-bh(l)')
                call b%line('prod(l) = '//chars(terms(k)))
                call b%line('residual(l) = (((ah(l)*bh(l)-prod(l))+'// &
                            'ah(l)*bl(l))+al(l)*bh(l))+al(l)*bl(l)')
                entry = chars(right(k))
                entry = 'a_low'//entry(2:)
                call b%line('residual(l) = residual(l) + '//chars(left(k))// &
                            '*'//entry)
                call b%line('term(l) = prod(l) - correction(l)')
                call b%line('next(l) = z(l,j+1) + term(l)')
                call b%line('correction(l) = ((next(l)-z(l,j+1))-term(l))-residual(l)')
                call b%line('z(l,j+1) = next(l)')
                call b%line('end do')
            end do
            call b%line('!$omp simd')
            call b%line('do l = 1, nc')
            call b%line('z_low(l,j+1) = -correction(l)')
            call b%line('end do')
        else
            call b%line('z(l,j+1) = '//balanced_sum(terms))
            call b%line('end do')
        end if
        call b%line('end do')
        call copy_cpu(b, 'a(l,j)', 'z(l,j)', total)
        if (t%precision == PRECISION_REAL32) &
            call copy_cpu(b, 'a_low(l,j)', 'z_low(l,j)', total)
    end subroutine stage_cpu

    function emit_tensor_cuda(ir, leaf, t, ok, message) result(source)
        type(kernel_ir_t), intent(in) :: ir
        type(kernel_emit_spec_t), intent(in) :: leaf
        type(tensor_kernel_spec_t), intent(in) :: t
        logical, intent(out) :: ok
        character(:), allocatable, intent(out) :: message
        type(str_t) :: source, scalar
        type(kernel_emit_spec_t) :: ls
        type(buffer_t) :: b
        character(:), allocatable :: name, typ, args, nds, qs, vs, ms, off
        integer :: ch, axis, dims(3), nd, nqv, nm
        source = str('')
        call validate(t, leaf, ok, message)
        if (.not. ok) return
        name = chars(t%name)
        ls = leaf; ls%name = str(name//'_leaf'); ls%precision = t%precision
        scalar = emit_cuda_device_ir(ir, ls, ok, message)
        if (.not. ok) return
        typ = 'double'
        if (t%precision == PRECISION_REAL32) typ = 'float'
        nd = t%nloc**t%dimension; nqv = t%nq**t%dimension
        nm = t%nq*t%nloc*t%dimension
        nds = number(nd); qs = number(nqv)
        vs = number(max(t%nloc, t%nq)**t%dimension); ms = number(nm)
        call b%line('// Generated by FortGen tensor schedule. Do not edit.')
        call b%line('#include <cuda_runtime.h>')
        call b%line(chars(scalar))
        call b%line('extern "C" __global__ void '//name// &
                    '(int nc, const '//typ//'* u, const '//typ//'* b, const '// &
                    typ//'* db, const '//typ//'* coef, '//typ//'* y) {')
        call b%line('const int cell = blockIdx.x, j = threadIdx.x;')
        call b%line('if (cell >= nc) return;')
        call b%line('// Uniform rejection: every thread must cover one tensor index.')
        call b%line('if (blockDim.x < '//vs//' || blockDim.y != 1 || '// &
                    'blockDim.z != 1) return;')
        call b%line('__shared__ '//typ//' a['//vs//'], v['// &
                    number(nqv*(t%dimension + 1))//'], sb['//ms//'], sd['//ms//'];')
        off = '0'
        if (t%cell_tables) off = 'cell*'//ms
        call b%line('for (int i=j; i<'//ms//'; i+=blockDim.x) {')
        call b%line('sb[i]=b['//off//'+i]; sd[i]=db['//off//'+i]; }')
        call b%line('__syncthreads();')
        if (t%precision == PRECISION_REAL32) &
            call b%line('__shared__ float a_low['//vs//'];')
        call b%line(typ//' acc;')
        if (t%precision == PRECISION_REAL32) &
            call b%line('float correction, term, next, prod, residual;')
        do ch = 0, t%dimension
            call b%line('if (j<'//nds//') a[j]=u[cell*'//nds//'+j];')
            if (t%precision == PRECISION_REAL32) &
                call b%line('if (j<'//nds//') a_low[j]=0;')
            call b%line('__syncthreads();')
            dims = t%nloc
            do axis = 1, t%dimension
                call stage_cuda(b, t, dims, axis, ch, .false.)
            end do
            off = 'a[j]'
            if (t%precision == PRECISION_REAL32) off = '(a[j]+a_low[j])'
            call b%line('if (j<'//qs//') v['//number(ch*nqv)//'+j]='//off//';')
            call b%line('__syncthreads();')
        end do
        call b%line('if (j<'//qs//') {')
        do ch = 0, t%dimension
            call b%line(typ//' f'//number(ch)//';')
        end do
        args = ''
        do ch = 0, t%dimension
            args = args//'v['//number(ch*nqv)//'+j],'
        end do
        do ch = 1, t%ncoeff
            args = args//'coef[cell*'//number(nqv*t%ncoeff)//'+'// &
                   number((ch - 1)*nqv)//'+j],'
        end do
        do ch = 0, t%dimension
            args = args//'&f'//number(ch)
            if (ch /= t%dimension) args = args//','
        end do
        call b%line(name//'_leaf('//args//');')
        do ch = 0, t%dimension
            call b%line('v['//number(ch*nqv)//'+j]=f'//number(ch)//';')
        end do
        call b%line('}')
        call b%line('if (j<'//nds//') y[cell*'//nds//'+j]=0;')
        call b%line('__syncthreads();')
        do ch = 0, t%dimension
            call b%line('if (j<'//qs//') a[j]=v['//number(ch*nqv)//'+j];')
            if (t%precision == PRECISION_REAL32) &
                call b%line('if (j<'//qs//') a_low[j]=0;')
            call b%line('__syncthreads();')
            dims = t%nq
            do axis = t%dimension, 1, -1
                call stage_cuda(b, t, dims, axis, ch, .true.)
            end do
            off = 'a[j]'
            if (t%precision == PRECISION_REAL32) off = '(a[j]+a_low[j])'
            call b%line('if (j<'//nds//') y[cell*'//nds//'+j]+='//off//';')
            call b%line('__syncthreads();')
        end do
        call b%line('}')
        source = str(b%str())
    end function

    subroutine stage_cuda(b, t, dims, axis, ch, transpose)
        type(buffer_t), intent(inout) :: b
        type(tensor_kernel_spec_t), intent(in) :: t
        integer, intent(inout) :: dims(3)
        integer, intent(in) :: axis, ch
        logical, intent(in) :: transpose
        integer :: stride, ni, no, total, k
        type(str_t), allocatable :: terms(:)
        character(:), allocatable :: idx, mat, mi, term_text
        integer :: split_at
        stride = product(dims(:axis - 1))
        ni = dims(axis)
        no = t%nq
        if (transpose) no = t%nloc
        dims(axis) = no
        total = product(dims(:t%dimension))
        mat = 'sb'
        if (ch == axis) mat = 'sd'
        allocate (terms(ni))
        do k = 0, ni - 1
            idx = '(j%'//number(stride)//')+'//number(stride)// &
                  '*('//number(k)//'+'//number(ni)//'*(j/'// &
                  number(stride*no)//'))'
            if (transpose) then
                mi = number(k)//'+'//number(t%nq)//'*qi'
            else
                mi = 'qi+'//number(t%nq*k)
            end if
            mi = mi//'+'//number((axis - 1)*t%nq*t%nloc)
            terms(k + 1) = str(mat//'['//mi//']*a['//idx//']')
        end do
        call b%line('acc=0;')
        call b%line('if (j<'//number(total)//') {')
        call b%line('const int qi=(j/'//number(stride)//')%'//number(no)//';')
        if (t%precision == PRECISION_REAL32) then
            call b%line('correction = 0;')
            do k = 1, ni
                call b%line('prod = '//chars(terms(k))//';')
                term_text = chars(terms(k))
                split_at = index(term_text, '*a[')
                call b%line('residual = fmaf('//term_text(:split_at - 1)//','// &
                            term_text(split_at + 1:)//',-prod);')
                call b%line('residual += '//term_text(:split_at - 1)// &
                            '*a_low'//term_text(split_at + 2:)//';')
                call b%line('term = prod - correction;')
                call b%line('next = acc + term;')
                call b%line('correction = ((next - acc) - term) - residual;')
                call b%line('acc = next;')
            end do

        else
            call b%line('acc = '//balanced_sum(terms)//';')
        end if
        call b%line('}')
        call b%line('__syncthreads();')
        call b%line('if (j<'//number(total)//') a[j]=acc;')
        if (t%precision == PRECISION_REAL32) &
            call b%line('if (j<'//number(total)//') a_low[j]=-correction;')
        call b%line('__syncthreads();')
    end subroutine stage_cuda
end module fortgen_tensor_emit
